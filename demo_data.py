def get_demo_records(now=None):
    """Возвращает список записей, разобранных из встроенных тестовых сообщений."""
    now = now or datetime.now()
    records = []
    for subchat, text, hours_ago in _DEMO_MESSAGES:
        rec = parse_message(text.strip(), subchat=subchat, message_date=now - timedelta(hours=hours_ago))
        if rec:
            records.append(rec)
    return records
